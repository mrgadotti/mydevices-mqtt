"""Extracts the app's own UI strings from the decoded APK into src/i18n/original.ts.
usage: python3 tools/extract-strings.py <decoded>/res/values/strings.xml src/i18n/original.ts
"""
import html
import json
import re
import sys

src, out = sys.argv[1:3]
xml = open(src, encoding="utf8").read()
skip = ("abc_", "common_", "status_bar", "search_", "mtrl_", "design_", "appbar", "character_counter",
        "password_toggle", "bottom_sheet", "fab_transformation", "hide_bottom", "ic_", "rate_dialog",
        "crashlytics", "com.crashlytics", "fcm", "firebase", "gcm", "google", "copy", "paste", "cut",
        "select_all", "TAG_", "v7_preference", "handle_rotation", "cant_initialize", "cant_configure",
        "unsibscribed_from")

def clean(raw: str) -> str:
    v = html.unescape(raw)
    if len(v) >= 2 and v[0] == '"' and v[-1] == '"':
        v = v[1:-1]
    return v.replace("\\n", "\n").replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\")

lines = ["// Generated by tools/extract-strings.py from the original app's res/values/strings.xml. Do not edit.",
         "export const S_EN = {"]
for name, raw in re.findall(r'<string name="([^"]+)">(.*?)</string>', xml, re.S):
    if name.startswith(skip) or "." in name:
        continue
    key = name if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name) else json.dumps(name)
    lines.append(f"  {key}: {json.dumps(clean(raw), ensure_ascii=False)},")
lines.append("} as const;")
lines.append("")
open(out, "w", encoding="utf8").write("\n".join(lines))
print(f"{len(lines) - 3} strings -> {out}")
